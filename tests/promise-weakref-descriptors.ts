export {};
let resolve!: (value: number) => void;
const pending = new Promise<number>(done => {resolve = done;});
Object.defineProperty(pending, 'label', {value: 'pending', enumerable: true, configurable: true});
const frozen = Object.freeze(pending);
console.log('promise frozen', frozen === pending, Object.isFrozen(pending), Object.keys(pending).join(','), Promise.resolve(pending) === pending);
console.log('promise properties', Reflect.set(pending, 'label', 'changed'), Reflect.defineProperty(pending, 'extra', {value: 1}));
pending.then(value => console.log('fulfilled', value, (pending as any).label));
resolve(7);
console.log('settled asynchronously');
const rejected = Promise.reject('reason');
Object.freeze(rejected);
rejected.catch(reason => console.log('rejected', reason));
const target = {value: 9};
const reference = new WeakRef(target);
Object.defineProperty(reference, 'label', {get() {return this.deref()!.value;}, enumerable: true});
Object.freeze(reference);
console.log('weakref', reference.deref() === target, (reference as any).label, Object.isFrozen(reference), Object.keys(reference).join(','));
console.log('weakref properties', Reflect.deleteProperty(reference, 'label'), Reflect.defineProperty(reference, 'extra', {value: 1}));
