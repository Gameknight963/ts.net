    static bool NativeTimeZoneAvailable(string name)
    {
        try {System.TimeZoneInfo.FindSystemTimeZoneById(name); return true;}
        catch (System.TimeZoneNotFoundException) {return false;}
        catch (System.InvalidTimeZoneException) {return false;}
    }
    static object LocaleTimeZones(LocaleValue locale)
    {
        if (locale.Region == null) return Undefined;
        var result = new JsArray(0);
        if (!LocaleTimeZoneData.Regions.TryGetValue(locale.Region, out var zones)) return result;
        string[] supported = IntlValueLists.TimeZones.Value;
        foreach (string zone in zones) if (locale.Region == "001" ? NativeTimeZoneAvailable(zone) : Array.BinarySearch(supported, zone, StringComparer.Ordinal) >= 0) result.Append(zone);
        return result;
    }
